const ids = new Set([...POLITIES.map((p) => p.id), 'qin']);
const nextPolities = polities.filter((p) => !ids.has(p.id));
const nextReigns = reigns.filter((r) => !ids.has(r.polityId));
const nextEras = eras.filter((e) => !ids.has(e.polityId));

const qin = polities.find((p) => p.id === 'qin');
const newPolities = POLITIES.map((p) => ({
  id: p.id,
  name: p.name,
  fullName: p.fullName,
  startYear: year(p.start),
  endYear: year(p.end),
  color: p.color,
  note: p.note,
  sources: ['S11'],
}));
newPolities.push({
  id: 'qin',
  name: qin.name,
  fullName: '秦（嬴秦）',
  startYear: year('前770'),
  endYear: qin.endYear,
  color: qin.color,
  note: '本表自秦襄公受封诸侯起纪；前 221 年嬴政并六国称皇帝，前 206 年子婴出降，秦亡。',
  sources: ['S11'],
});

let reignCount = 0;
for (const [polityId, list] of Object.entries(REIGNS)) {
  for (const [title, name, from, to] of list) {
    const startYear = year(from);
    const endYear = year(to);
    const rid = `${polityId}-${title}-${startYear}`;
    nextReigns.push({ id: rid, polityId, title, name, startYear, endYear });
    nextEras.push({
      id: `${polityId}-无年号-${title}-${startYear}`,
      polityId,
      name: '无年号',
      reignIds: [rid],
      startYear,
      endYear,
      sources: ['S11'],
    });
    reignCount++;
  }
}

// 时间轴由早到晚：把先秦政权排在文件前部
const byStart = (a, b) => a.startYear - b.startYear;
write('polities.json', [...newPolities, ...nextPolities].sort((a, b) => (a.startYear === b.startYear ? a.id.localeCompare(b.id) : byStart(a, b))));
write('reigns.json', [...nextReigns].sort(byStart));
write('eras.json', [...nextEras].sort(byStart));

console.log(`政权 +${newPolities.length}（含秦扩展），在位 +${reignCount}，纪年 +${reignCount}`);
