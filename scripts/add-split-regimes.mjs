const managed = new Set(POLITIES.map((p) => p.id));
const pulpit = (pid, title, name, start) => `${pid}-${title}-${name}-${start}`;

const polities = read('polities.json').filter((p) => !managed.has(p.id));
const reigns = read('reigns.json').filter((r) => !managed.has(r.polityId));
const eras = read('eras.json').filter((e) => !managed.has(e.polityId));

polities.push(...POLITIES);

for (const [pid, title, name, startYear, endYear, note] of REIGNS) {
  const id = pulpit(pid, title, name, startYear);
  if (reigns.some((r) => r.id === id)) throw new Error(`reign id 重复：${id}`);
  reigns.push({ id, polityId: pid, title, name, startYear, endYear, ...(note ? { note } : {}) });
}

for (const [pid, name, rulers, startYear, endYear, note, sources] of ERAS) {
  const id = `${pid}-${name}-${startYear}`;
  const reignIds = rulers.map(([title, name, start]) => {
    const rid = pulpit(pid, title, name, start);
    if (!reigns.some((r) => r.id === rid)) throw new Error(`纪年 ${id} 引用不存在的君主：${rid}`);
    return rid;
  });
  eras.push({ id, polityId: pid, name, reignIds, startYear, endYear, ...(note ? { note } : {}), sources });
}

write('polities.json', polities);
write('reigns.json', reigns);
write('eras.json', eras);

const count = (id) => ({
  reigns: reigns.filter((r) => r.polityId === id).length,
  eras: eras.filter((e) => e.polityId === id).length,
});
console.log(`政权 ${polities.length}（新增 ${POLITIES.length}）· 君主 ${reigns.length} · 纪年 ${eras.length}`);
for (const p of POLITIES) {
  const c = count(p.id);
  console.log(`  ${p.name} ${p.startYear}—${p.endYear}：${c.reigns} 位君主 / ${c.eras} 条纪年`);
}
