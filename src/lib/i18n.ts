/**
 * 界面语言：简体 / 繁体 / English。
 * - 中文文案以简体存放；繁体由 OpenCC 在运行时按需转换（只在选中繁体时加载字典）。
 * - 英文只译界面，史实数据（政权、年号、事件）保留中文原名。
 */
export type Lang = 'zh-Hans' | 'zh-Hant' | 'en';

export const LANGS: Lang[] = ['zh-Hans', 'zh-Hant', 'en'];
const STORAGE_KEY = 'chronochina-lang';

let current: Lang = 'zh-Hans';
let cn2t: ((text: string) => string) | null = null;
let t2cn: ((text: string) => string) | null = null;
const cache = new Map<string, string>();

export function getLang(): Lang {
  return current;
}

export function isHant(): boolean {
  return current === 'zh-Hant';
}

export function normalizeLang(tag: string | null | undefined): Lang | null {
  if (!tag) return null;
  const v = tag.trim().toLowerCase().replace(/_/g, '-');
  if (v.startsWith('zh')) return /hant|tw|hk|mo/.test(v) ? 'zh-Hant' : 'zh-Hans';
  if (v.startsWith('en')) return 'en';
  return null;
}

/** ?lang= 优先，其次本地记忆，最后跟随浏览器；非中文浏览器落到英文 */
export function detectLang(): Lang {
  if (typeof location !== 'undefined') {
    const fromUrl = normalizeLang(new URLSearchParams(location.search).get('lang'));
    if (fromUrl) return fromUrl;
  }
  try {
    const saved = normalizeLang(localStorage.getItem(STORAGE_KEY));
    if (saved) return saved;
  } catch {}
  if (typeof navigator !== 'undefined') return normalizeLang(navigator.language) ?? 'en';
  return 'zh-Hans';
}

export function rememberLang(lang: Lang) {
  try { localStorage.setItem(STORAGE_KEY, lang); } catch {}
}

export async function loadConverters(): Promise<void> {
  if (cn2t && t2cn) return;
  const [toTrad, toSimp] = await Promise.all([import('opencc-js/cn2t'), import('opencc-js/t2cn')]);
  cn2t = toTrad.Converter({ from: 'cn', to: 't' });
  t2cn = toSimp.Converter({ from: 't', to: 'cn' });
}

export async function ensureLang(lang: Lang): Promise<Lang> {
  if (lang === 'zh-Hant') await loadConverters();
  return lang;
}

export function applyLang(lang: Lang) {
  if (lang !== current) cache.clear();
  current = lang;
  if (typeof document !== 'undefined') {
    document.documentElement.lang = lang;
    document.title = t('doc.title');
  }
}

/** 简体 → 繁体（数据文本与中文界面共用）；英文模式下原样返回 */
export function S<T extends string | null | undefined>(text: T): T extends string ? string : T {
  if (text === null || text === undefined) return text as never;
  if (current !== 'zh-Hant' || !cn2t || !text) return text as never;
  const hit = cache.get(text);
  if (hit !== undefined) return hit as never;
  const out = cn2t(text);
  cache.set(text, out);
  return out as never;
}

